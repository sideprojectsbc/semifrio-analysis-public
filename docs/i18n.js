let lang = 'pt';
export const getLang = () => lang;
export function setLang(l) {
  lang = DICT[l] ? l : 'pt';
  document.documentElement.lang = lang;
  try { localStorage.setItem('semifrio-lang', lang); } catch { /* storage blocked: fine */ }
}
export function initLang() {
  try { const saved = localStorage.getItem('semifrio-lang'); if (DICT[saved]) lang = saved; } catch { /* ignore */ }
  document.documentElement.lang = lang;
}

export function t(key, params = {}) {
  const v = DICT[lang][key] ?? DICT.en[key];
  if (v === undefined) return key;
  return typeof v === 'function' ? v(params) : v;
}

// A number written the local way: 7.66 -> "7,7" (Portuguese) or "7.7" (English).
export const num = (v, digits = 1) =>
  (v === null || v === undefined || Number.isNaN(Number(v)) ? '–'
    : Number(v).toLocaleString(lang === 'pt' ? 'pt-PT' : 'en-GB', { maximumFractionDigits: digits, minimumFractionDigits: 0 }));

// Fills the fixed texts of index.html.
export function applyStatic() {
  document.title = t('title');
  for (const n of document.querySelectorAll('[data-i18n]')) n.innerHTML = t(n.dataset.i18n);
  // The contact address is put together here, not written out in the page, so simple bots cannot collect it.
  for (const a of document.querySelectorAll('a.contact')) {
    const address = ['sideprojectsbc', 'gmail.com'].join('@');
    a.href = `mailto:${address}`;
    a.textContent = address;
  }
  for (const n of document.querySelectorAll('[data-i18n-title]')) n.title = t(n.dataset.i18nTitle);
  for (const n of document.querySelectorAll('[data-i18n-ph]')) n.placeholder = t(n.dataset.i18nPh);
}
